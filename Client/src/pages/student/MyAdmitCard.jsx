import { useState, useEffect } from "react";
import api from "../../api/axiosConfig";
import { Loader2, FileBadge, Download, AlertTriangle } from "lucide-react";

const MyAdmitCard = () => {
  const [admitCards, setAdmitCards] = useState([]);
  const [loading, setLoading] = useState(true);

  const fetchAdmitCards = async () => {
    try {
      const res = await api.get("/student/portal/my-admit-cards");
      setAdmitCards(res.data);
    } catch (err) {
      console.error(err);
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    fetchAdmitCards();
  }, []);

  const downloadPDF = () => {
    window.print(); // Simple way to generate PDF for the demo
  };

  if (loading) {
    return <div className="flex justify-center p-12"><Loader2 className="animate-spin text-blue-500" size={32}/></div>;
  }

  return (
    <div className="space-y-8 print:space-y-0">
      <div className="flex items-center justify-between print:hidden">
        <h1 className="text-2xl font-bold text-slate-800 flex items-center gap-2">
          <FileBadge className="text-blue-500" /> My Admit Cards
        </h1>
      </div>

      {admitCards.length === 0 ? (
        <div className="bg-amber-50 border border-amber-200 rounded-3xl p-8 flex flex-col items-center text-center print:hidden">
          <AlertTriangle size={48} className="text-amber-500 mb-4" />
          <h2 className="text-xl font-bold text-amber-800 mb-2">No Admit Card Available</h2>
          <p className="text-amber-700">
            Admit Card is unavailable. Please ensure you have registered for an exam and completed your fee payment. 
            Admit cards are generated by the admin after fee verification.
          </p>
        </div>
      ) : (
        <div className="space-y-8">
          {admitCards.map((card, index) => (
            <div key={card._id} className="bg-white rounded-3xl p-8 shadow-lg border border-slate-200 max-w-2xl mx-auto print:shadow-none print:border-none print:w-full">
              
              {/* Admit Card Header */}
              <div className="text-center border-b-2 border-slate-200 pb-6 mb-6">
                <h2 className="text-2xl font-black text-slate-800 uppercase tracking-widest">Admit Card</h2>
                <h3 className="text-lg font-bold text-blue-600 mt-2">{card.exam?.name}</h3>
              </div>

              {/* Admit Card Details */}
              <div className="grid grid-cols-2 gap-y-6 gap-x-4 mb-8">
                <div>
                  <div className="text-xs text-slate-400 font-bold uppercase tracking-wider mb-1">Student Name</div>
                  <div className="font-bold text-slate-800">{card.student?.name || "Student Name"}</div>
                </div>
                <div>
                  <div className="text-xs text-slate-400 font-bold uppercase tracking-wider mb-1">Registration No</div>
                  <div className="font-bold text-slate-800">{card.student?.registrationNumber || "REG-XXX"}</div>
                </div>
                <div>
                  <div className="text-xs text-slate-400 font-bold uppercase tracking-wider mb-1">Roll No</div>
                  <div className="font-bold text-slate-800">{card.student?.rollNumber || "ROLL-XXX"}</div>
                </div>
                <div>
                  <div className="text-xs text-slate-400 font-bold uppercase tracking-wider mb-1">Exam Date</div>
                  <div className="font-bold text-slate-800">{new Date(card.exam?.date).toLocaleDateString()}</div>
                </div>
                <div className="col-span-2">
                  <div className="text-xs text-slate-400 font-bold uppercase tracking-wider mb-1">Exam Center</div>
                  <div className="font-bold text-slate-800">{card.exam?.center}</div>
                </div>
                <div className="col-span-2">
                  <div className="text-xs text-slate-400 font-bold uppercase tracking-wider mb-1">Subjects</div>
                  <div className="font-medium text-slate-700">{card.exam?.subjects?.join(", ")}</div>
                </div>
              </div>

              {/* QR Code / Unique ID Placeholder */}
              <div className="flex flex-col items-center justify-center p-6 bg-slate-50 rounded-2xl border border-slate-200 border-dashed">
                 <div className="w-32 h-32 bg-white border-4 border-slate-800 flex items-center justify-center mb-4">
                   <div className="grid grid-cols-3 gap-1">
                     {/* Pseudo QR Code Pattern */}
                     {[...Array(9)].map((_, i) => <div key={i} className={`w-3 h-3 ${Math.random() > 0.5 ? 'bg-slate-800' : 'bg-transparent'}`}></div>)}
                   </div>
                 </div>
                 <div className="text-xs font-mono font-bold text-slate-500">{card.uniqueId}</div>
              </div>

              {/* Action */}
              <div className="mt-8 flex justify-center print:hidden">
                <button onClick={downloadPDF} className="px-8 py-3 bg-blue-600 text-white font-bold rounded-xl shadow-lg shadow-blue-200 hover:bg-blue-700 transition-colors flex items-center gap-2">
                  <Download size={20} /> Download PDF
                </button>
              </div>

            </div>
          ))}
        </div>
      )}
    </div>
  );
};

export default MyAdmitCard;
